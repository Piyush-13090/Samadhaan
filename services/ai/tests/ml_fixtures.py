"""Small synthetic datasets for the ML pipeline tests (Prompt 28).

Generated, deterministic and labelled `synthetic: true`. They exercise the
pipeline; any metric computed on them says nothing about real-world accuracy.
"""

from __future__ import annotations

import json
import random
from pathlib import Path
from typing import Any

VOCAB = {
    "POTHOLES": ["pothole", "crater", "tyre", "asphalt", "cavity", "bump"],
    "STREETLIGHTS": ["streetlight", "lamp", "dark", "bulb", "pole", "unlit"],
    "GARBAGE": ["garbage", "waste", "bin", "dumping", "stink", "rubbish"],
    "WATER": ["water", "supply", "tap", "pipeline", "leak", "pressure"],
    "DRAINAGE": ["drain", "sewage", "overflow", "clogged", "waterlogging", "gutter"],
}
FILLER = ["near", "the", "market", "school", "road", "since", "week", "residents", "lane", "corner"]
CITIES = ["Pune", "Nagpur", "Nashik", "Thane"]
SEVERITY_WORDS = {
    "LOW": ["minor", "small", "cosmetic"],
    "MEDIUM": ["growing", "annoying", "disruptive"],
    "HIGH": ["dangerous", "injury", "accident"],
    "CRITICAL": ["collapsed", "electrocution", "emergency"],
}


def manifest(task: str, records_file: str = "records.jsonl", **overrides: Any) -> dict[str, Any]:
    base = {
        "name": f"synthetic-{task.replace('_', '-')}",
        "version": "v1",
        "task": task,
        "records_file": records_file,
        "description": "Synthetic fixture for pipeline tests.",
        "owner": "samadhaan-tests",
        "permitted_uses": ["training", "evaluation"],
        "retention": "test lifetime",
        "collection": "Generated by tests/ml_fixtures.py",
        "consent_basis": "synthetic, no people",
        "contains_personal_data": False,
        "synthetic": True,
        "created_at": "2026-10-18T00:00:00Z",
    }
    return {**base, **overrides}


def write_dataset(root: Path, task: str, records: list[dict[str, Any]], **overrides: Any) -> Path:
    root.mkdir(parents=True, exist_ok=True)
    (root / "dataset.json").write_text(json.dumps(manifest(task, **overrides)))
    (root / "records.jsonl").write_text("".join(json.dumps(r) + "\n" for r in records))
    return root


def category_records(per_class: int = 40, seed: int = 7) -> list[dict[str, Any]]:
    rng = random.Random(seed)
    out = []
    for category, words in VOCAB.items():
        for i in range(per_class):
            picked = rng.sample(words, 3) + rng.sample(FILLER, 3)
            rng.shuffle(picked)
            out.append(
                {
                    "record_id": f"{category.lower()}-{i:03d}",
                    "title": f"{picked[0]} {picked[1]} problem",
                    "description": " ".join(picked) + f" report number {i}",
                    "category": category,
                    "label_source": "HUMAN_REVIEWED",
                    "city": CITIES[i % len(CITIES)],
                    "created_at": f"2026-0{1 + i % 9}-{10 + i % 18:02d}T08:00:00Z",
                    "baseline_category": category if i % 4 else "OTHER",
                }
            )
    return out


def severity_records(per_class: int = 40, seed: int = 11) -> list[dict[str, Any]]:
    rng = random.Random(seed)
    out = []
    for severity, words in SEVERITY_WORDS.items():
        for i in range(per_class):
            category = list(VOCAB)[i % len(VOCAB)]
            picked = rng.sample(words, 2) + rng.sample(VOCAB[category], 2) + rng.sample(FILLER, 2)
            out.append(
                {
                    "record_id": f"sev-{severity.lower()}-{i:03d}",
                    "title": " ".join(picked[:3]),
                    "description": " ".join(picked) + f" case {i}",
                    "category": category,
                    "severity": severity,
                    "label_source": "EXPERT_ADJUDICATED",
                    "city": CITIES[i % len(CITIES)],
                    "created_at": f"2026-{1 + (i * 7) % 12:02d}-{1 + i % 27:02d}T00:00:00Z",
                }
            )
    return out


def duplicate_records(pairs: int = 240, seed: int = 3) -> list[dict[str, Any]]:
    rng = random.Random(seed)
    out = []
    for i in range(pairs):
        duplicate = i % 3 == 0
        text = rng.uniform(0.75, 0.98) if duplicate else rng.uniform(0.1, 0.8)
        geo = rng.uniform(0.6, 1.0) if duplicate else rng.uniform(0.0, 0.7)
        out.append(
            {
                "record_id": f"pair-{i:04d}",
                "problem_a": f"p{i * 2:05d}",
                "problem_b": f"p{i * 2 + 1:05d}",
                "text_similarity": round(text, 4),
                "geographic_similarity": round(geo, 4),
                "category_similarity": 1.0 if duplicate or i % 2 else 0.0,
                "baseline_score": round(0.5 * text + 0.5 * geo, 4),
                "is_duplicate": duplicate,
                "label_source": "HUMAN_REVIEWED",
            }
        )
    return out
